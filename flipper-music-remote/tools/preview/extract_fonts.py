#!/usr/bin/env python3
"""Decode the Flipper's u8g2 fonts out of the SDK firmware.elf into a C glyph table
for the desktop preview.  Usage: extract_fonts.py ~/.ufbt/current/firmware.elf > fonts.h"""
import sys

RODATA_ADDR, RODATA_OFF = 0x08093748, 0x0937E8
FONTS = {"primary": (0x080BAF7B, 0x426), "secondary": (0x080BABC9, 0x3B2)}


class Bits:
    def __init__(self, data, pos):
        self.d, self.p, self.b = data, pos, 0

    def u(self, n):
        val = self.d[self.p] >> self.b
        nb = self.b + n
        if nb >= 8:
            self.p += 1
            val |= self.d[self.p] << (8 - self.b)
            nb -= 8
        self.b = nb
        return val & ((1 << n) - 1)

    def s(self, n):
        return self.u(n) - (1 << (n - 1))


def decode(font):
    h = font[:23]
    bp0, bp1, bw, bh, bx, by, bd = h[2:9]
    ascent = h[13] if h[13] < 128 else h[13] - 256
    glyphs = {}
    p = 23
    while font[p + 1] != 0:
        enc, jump = font[p], font[p + 1]
        r = Bits(font, p + 2)
        w, hh, x, y, dx = r.u(bw), r.u(bh), r.s(bx), r.s(by), r.s(bd)
        px = [[0] * w for _ in range(hh)]
        if w > 0:
            cx = cy = 0
            def run(n, c):
                nonlocal cx, cy
                for _ in range(n):
                    if cy < hh and c:
                        px[cy][cx] = 1
                    cx += 1
                    if cx >= w:
                        cx, cy = 0, cy + 1
            while cy < hh:
                a, b = r.u(bp0), r.u(bp1)
                while True:
                    run(a, 0)
                    run(b, 1)
                    if r.u(1) == 0:
                        break
        glyphs[enc] = (w, hh, x, y, dx, px)
        p += jump
    return ascent, glyphs


elf = open(sys.argv[1], "rb").read()
print("/* generated by extract_fonts.py — Flipper u8g2 fonts */\n#pragma once\n#include <stdint.h>")
print("typedef struct { int8_t w, h, x, y, dx; uint16_t rows[16]; } PGlyph;")
for name, (addr, size) in FONTS.items():
    off = RODATA_OFF + addr - RODATA_ADDR
    ascent, glyphs = decode(elf[off:off + size])
    print(f"static const int font_{name}_ascent = {ascent};")
    print(f"static const PGlyph font_{name}[128] = {{")
    for c in range(128):
        if c in glyphs:
            w, hh, x, y, dx, px = glyphs[c]
            rows = [sum(bit << (15 - i) for i, bit in enumerate(row)) for row in px][:16]
            print(f"  [{c}] = {{{w},{hh},{x},{y},{dx},{{{','.join(map(str, rows)) or '0'}}}}},")
    print("};")
